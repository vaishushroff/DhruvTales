export const SEED_EPISODES: Episode[] = SEED_STORIES.flatMap((story) => {
  const customBlueprints = EPISODE_BLUEPRINTS[story.id];
  return Array.from({ length: story.episodeCount }, (_, idx) => {
    const epNum = idx + 1;
    const template = customBlueprints?.[idx] ?? GENERIC_ARC[idx % GENERIC_ARC.length];

    // Interactive branching stories keep all branches free so full playthroughs never stall mid-choice.
    // Standard serialized stories: Ep 1-2 Free (0 coins), Ep 3-4 10 coins, Ep 5+ 20 coins.
    const priceCoins = story.isInteractive
      ? 0
      : epNum <= 2
        ? 0
        : epNum <= 4
          ? 10
          : 20;

    const epId = `${story.id}-ep-${epNum}`;
    const audioRef = {
      provider: 'demo' as const,
      id: `dt-audio-${story.slug}-ep${epNum}`,
      type: 'audio' as const,
    };

    const baseEpisode: Episode = {
      id: epId,
      storyId: story.id,
      creatorOwnerUid: story.creatorOwnerUid,
      episodeNumber: epNum,
      title: template.en,
      titleHi: template.hi,
      description: template.descEn,
      descriptionHi: template.descHi,
      durationSec: template.dur,
      priceCoins,
      mediaRef: audioRef,
      audioRef,
      publishedAt: story.publishedAt,
    };

    const includeVideo =
      typeof template.hasVideo === 'boolean'
        ? template.hasVideo
        : story.format === 'hybrid' && epNum <= 3;

    if (includeVideo) {
      baseEpisode.videoMediaRef = {
        provider: 'demo',
        id: `dt-video-${story.slug}-ep${epNum}`,
        type: 'video',
      };
    }

    if (template.choicePoint) {
      baseEpisode.choicePoint = template.choicePoint;
    }

    if (template.isEnding) {
      baseEpisode.isEnding = true;
    }

    return baseEpisode;
  });
});
